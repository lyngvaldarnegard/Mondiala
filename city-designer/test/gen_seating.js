// gen_seating.js — the v3.0 seating-table generator: runs the placement formulas once,
// for all three modes in both orientations, to the full depth of the roster (ring 12 —
// no dry frontier), and writes ../mondiala-seating.js. The page only reads the result:
// no expensive compute ever runs at load or at click. Roster edit = re-run sh test/regen.sh
// and commit the regenerated table. Concatenated after loader.js by run.sh and regen.sh.
"use strict";
function __genSeating(write) {
  const X = globalThis.__X;
  const prev = { placeMode: X.placeMode, GRID_ROT: X.GRID_ROT, maxCircle: X.maxCircle };
  const out = {};
  for (const mode of ["neighbours", "hexagonal"]) {
    out[mode] = {};
    for (const rot of [30, 0]) {
      X.placeMode = mode; X.GRID_ROT = rot; X.maxCircle = 10; // v3.5: the cleanup — rings 5-10 hold all 210; the pool is empty, nothing beyond
      const plan = X.computeWorldPlan();
      const rings = {};
      for (let c = 5; c <= 10; c++) rings[c] = (plan.plan[c] || []).slice().sort((a, b) => a[0] - b[0]);
      out[mode][rot ? "pointy" : "flat"] = {
        center: { lat: +plan.center.lat.toFixed(8), lon: +plan.center.lon.toFixed(8) },
        rings, leftover: plan.leftover
      };
    }
  }
  X.placeMode = prev.placeMode; X.GRID_ROT = prev.GRID_ROT; X.maxCircle = prev.maxCircle;
  if (write) {
    const body = "// mondiala-seating.js — v3.0 formula-generated seating tables (instant load).\n"
      + "// GENERATED by city-designer/test/gen_seating.js — never hand-edit.\n"
      + "// After any roster or formula edit: sh test/regen.sh, then commit the regenerated table.\n"
      + "// One table per placement mode, per orientation: city -> ring.hexagon, to the full depth of the roster.\n"
      + "const SEATING = " + JSON.stringify(out, null, 1) + ";\n";
    require("fs").writeFileSync("../mondiala-seating.js", body, "utf8");
    console.log("mondiala-seating.js written: " + body.length + " chars");
  }
  return out;
}
